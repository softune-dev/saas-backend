-- =============================================================================
-- 087_free_plan.sql: groundwork for the Free plan.
--
--   1. tenants.plan may be 'free'.
--   2. tenants.last_active_at: when the merchant last did something real, so a
--      later sweep can tell an abandoned free store from a live one. NOT NULL
--      DEFAULT now(): every existing tenant's clock starts at the moment this
--      runs, so nobody looks inactive because of a column that did not exist.
--   3. tenant_order_months: orders per tenant per calendar month, the counter a
--      free plan's monthly order limit is enforced against. `blocked` counts
--      orders refused after the limit was hit (shown to the merchant so they
--      see what the limit cost them).
--   4. marketing_contacts.lifecycle may be 'free'.
--   5. notifications.type may be 'order_limit' (limit reached) and
--      'order_flagged'. The latter was already being published by
--      app/api/public.py for fraud-flagged orders but was never in the CHECK,
--      so the insert failed (and notifications.py dropped it as "unknown").
--
-- SAFE TO RUN WHILE THE OLD CODE IS LIVE: additive only. Every new column has a
-- default, so the old code's INSERTs (which do not name them) keep working. Each
-- CHECK is WIDENED: the previous values are copied verbatim, so no existing row
-- or write can fail it.
--   tenants_plan_check            previous: 049 (trial, demo, starter, growth, business)
--   marketing_contacts lifecycle  previous: 077 (lead, trial, customer, churned, former_customer)
--   notifications_type_check      previous: 069 (order_created, order_blocked, site_published,
--                                                site_unpublished, payment_verified,
--                                                credit_purchase_verified)
--
-- Idempotent (re-runnable), one transaction. lock_timeout makes it fail cleanly
-- instead of queueing behind a long query and stalling production traffic; if it
-- fails, nothing was changed, just run it again. The tables are small, so
-- re-adding a CHECK (a quick scan under a brief lock) is fine; NOT VALID would
-- not shorten the lock because the transaction holds it until COMMIT anyway.
-- =============================================================================

BEGIN;

SET LOCAL lock_timeout = '5s';

-- 1. plans ---------------------------------------------------------------------
ALTER TABLE tenants DROP CONSTRAINT IF EXISTS tenants_plan_check;
ALTER TABLE tenants ADD CONSTRAINT tenants_plan_check
    CHECK (plan IN ('free', 'trial', 'demo', 'starter', 'growth', 'business'));

-- 2. activity clock ------------------------------------------------------------
-- No index: only read by a periodic sweep over a table of a few thousand rows;
-- add one if that ever stops being true.
ALTER TABLE tenants
    ADD COLUMN IF NOT EXISTS last_active_at timestamptz NOT NULL DEFAULT now();

-- 3. monthly order counter -----------------------------------------------------
CREATE TABLE IF NOT EXISTS tenant_order_months (
    tenant_id uuid    NOT NULL REFERENCES tenants(id) ON DELETE CASCADE,
    -- First day of the month the counts belong to.
    month     date    NOT NULL,
    orders    integer NOT NULL DEFAULT 0 CONSTRAINT tenant_order_months_orders_check  CHECK (orders  >= 0),
    blocked   integer NOT NULL DEFAULT 0 CONSTRAINT tenant_order_months_blocked_check CHECK (blocked >= 0),
    -- PK serves two queries: the atomic upsert "bump this tenant's counter for
    -- this month" and the limit check "read this tenant's row for this month".
    -- Its leading column tenant_id also serves the foreign key (cascade delete
    -- of a tenant finds its rows), so no separate FK index is needed.
    PRIMARY KEY (tenant_id, month)
);

-- Same reasoning as 046/054: the backend connects as postgres and bypasses RLS;
-- enabling it with no policies only walls off Supabase's public REST roles.
ALTER TABLE tenant_order_months ENABLE ROW LEVEL SECURITY;

-- 4. contact lifecycle ---------------------------------------------------------
-- The CHECK was declared inline in 077, so its name was generated by Postgres.
-- Find it by what it checks rather than guessing, then replace it under a fixed
-- name (this also makes a re-run replace our own constraint cleanly).
DO $$
DECLARE
    c record;
BEGIN
    FOR c IN
        SELECT conname
        FROM pg_constraint
        WHERE conrelid = 'marketing_contacts'::regclass
          AND contype = 'c'
          AND pg_get_constraintdef(oid) LIKE '%lifecycle%'
    LOOP
        EXECUTE format('ALTER TABLE marketing_contacts DROP CONSTRAINT %I', c.conname);
    END LOOP;
END $$;

ALTER TABLE marketing_contacts ADD CONSTRAINT marketing_contacts_lifecycle_check
    CHECK (lifecycle IN ('lead', 'trial', 'free', 'customer', 'churned', 'former_customer'));

-- 5. notification types --------------------------------------------------------
ALTER TABLE notifications DROP CONSTRAINT IF EXISTS notifications_type_check;
ALTER TABLE notifications ADD CONSTRAINT notifications_type_check
    CHECK (type IN (
        'order_created', 'order_blocked', 'site_published', 'site_unpublished',
        'payment_verified', 'credit_purchase_verified',
        'order_flagged', 'order_limit'
    ));

COMMIT;

